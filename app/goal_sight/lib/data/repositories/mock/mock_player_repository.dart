  @override
  Future<List<PlayerProfileModel>> fetchSquad({String? clubId}) async {
    await Future.delayed(_delay);
    if (clubId == null) return List.unmodifiable(_players);
    final ids = _clubPlayers[clubId] ?? [];
    return _players.where((p) => ids.contains(p.id)).toList();
  }

  @override
  Future<PlayerProfileModel> fetchPlayerById(String id) async {
    await Future.delayed(_delay);
    return _players.firstWhere(
      (p) => p.id == id,
      orElse: () => throw RepositoryException('Player not found: $id'),
    );
  }

  @override
  Future<RiskAnalysisModel> fetchRiskAnalysis(String playerId) async {
    await Future.delayed(_delay);
    final risk = _risks[playerId];
    if (risk == null) throw RepositoryException('Risk data not found: $playerId');
    return risk;
  }

  @override
  Future<List<RiskAnalysisModel>> fetchSquadRiskAnalysis({String? clubId}) async {
    await Future.delayed(_delay);
    final ids = clubId != null ? (_clubPlayers[clubId] ?? []) : _risks.keys.toList();
    return ids
        .where(_risks.containsKey)
        .map((id) => _risks[id]!)
        .toList()
      ..sort((a, b) => b.compositeScore.compareTo(a.compositeScore));
  }

  @override
  Future<List<PlayerProfileModel>> fetchPlayersPaged({
    required int page,
    int pageSize = 20,
    String? query,
    String? position,
    String sortBy = 'rating',
    bool descending = true,
  }) async {
    await Future.delayed(_delay);

    var list = List<PlayerProfileModel>.from(_players);

    // Filter
    if (query != null && query.isNotEmpty) {
      final lower = query.toLowerCase();
      list = list.where((p) => p.name.toLowerCase().contains(lower)).toList();
    }
    if (position != null && position.isNotEmpty) {
      list = list.where((p) => p.position.toUpperCase().contains(position.toUpperCase())).toList();
    }

    // Sort
    switch (sortBy) {
      case 'rating':
        list.sort((a, b) => a.currentRating.compareTo(b.currentRating));
      case 'fatigue':
        list.sort((a, b) => a.fatigue.compareTo(b.fatigue));
      case 'goals':
        list.sort((a, b) => a.totalGoals.compareTo(b.totalGoals));
      case 'assists':
        list.sort((a, b) => a.totalAssists.compareTo(b.totalAssists));
    }
    if (descending) list = list.reversed.toList();

    // Paginate
    final start = page * pageSize;
    final end = (start + pageSize).clamp(0, list.length);
    if (start >= list.length) return [];
    return list.sublist(start, end);
  }
